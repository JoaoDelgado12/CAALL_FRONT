/// <reference lib="webworker" />
import { cleanupOutdatedCaches, createHandlerBoundToURL, precacheAndRoute } from 'workbox-precaching';
import { clientsClaim } from 'workbox-core';
import { NavigationRoute, registerRoute } from 'workbox-routing';
import { NetworkFirst, CacheFirst, NetworkOnly } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';

declare let self: ServiceWorkerGlobalScope;

registerRoute(({ url }) => url.pathname.endsWith('/dictionary'), new NetworkOnly());

// Immediately take control of open clients on activation
self.skipWaiting();
clientsClaim();

// Clean old precaches from previous builds
cleanupOutdatedCaches();

// Precache all assets generated by Vite build (index.html, CSS, JS bundles)
precacheAndRoute(self.__WB_MANIFEST);

// Serve index.html for all navigation requests when offline (App Shell)
const fileExtensionRegexp = new RegExp('/[^/?]+\\.[^/]+$');
registerRoute(
  new NavigationRoute(createHandlerBoundToURL('/index.html'), {
    denylist: [fileExtensionRegexp],
  })
);

// Cache static images/icons with CacheFirst strategy
registerRoute(
  ({ request }) => request.destination === 'image',
  new CacheFirst({
    cacheName: 'caall-images-cache',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 60,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 Days
      }),
    ],
  })
);

// API requests: Try network first, do not fail SW if offline
registerRoute(
  ({ url }) => url.pathname.startsWith('/api/'),
  new NetworkFirst({
    cacheName: 'caall-api-fallback',
    networkTimeoutSeconds: 5,
  })
);